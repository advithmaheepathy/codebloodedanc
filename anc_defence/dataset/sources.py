"""Corpus registry, licence records and targeted downloaders.

Only what the small evaluation set needs is downloaded: individual ESC-50 clips for
the noise taxonomy, and a handful of LibriSpeech utterances for clean speech
(streamed out of the archive and stopped early rather than fetching the whole
337 MB tarball).

Every corpus used is recorded in :data:`CORPORA` with its licence, and
``anc licenses`` writes LICENSES.md from that list. Nothing whose terms are unclear
is bundled or downloaded.

If the network is unavailable, :func:`synthesise_fallback_corpus` generates
procedural stand-ins for every noise category so the pipeline is always runnable.
Synthetic speech is *not* substituted for real speech: PESQ and STOI on synthetic
speech would not mean anything, so the builder reports honestly instead.
"""

