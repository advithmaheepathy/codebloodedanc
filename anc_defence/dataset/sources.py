_ESC50_META_URL = "https://raw.githubusercontent.com/karolpiczak/ESC-50/master/meta/esc50.csv"
_ESC50_AUDIO_URL = "https://raw.githubusercontent.com/karolpiczak/ESC-50/master/audio/{name}"
_LIBRISPEECH_URL = "https://www.openslr.org/resources/12/dev-clean.tar.gz"


def _urlopen(url: str, timeout: float = 30.0):
    req = urllib.request.Request(url, headers={"User-Agent": _USER_AGENT})
    return urllib.request.urlopen(req, timeout=timeout)


def fetch_esc50_subset(
    out_dir: Path | str,
    per_class: int = 6,
    classes: Optional[Iterable[str]] = None,
    target_sr: int = 48000,
    timeout: float = 30.0,
) -> dict[str, list[Path]]:
    """Download a few ESC-50 clips per class, organised by our taxonomy.

    Returns ``{category: [paths]}``. Existing files are not re-downloaded.
    """
    out = Path(out_dir)
    wanted = list(classes) if classes is not None else list(ESC50_MAP)
    try:
        with _urlopen(_ESC50_META_URL, timeout) as resp:
            meta_text = resp.read().decode("utf-8")
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        log.warning("could not fetch the ESC-50 index (%s); falling back to synthetic noise", exc)
        return {}

    rows = list(csv.DictReader(io.StringIO(meta_text)))
    by_class: dict[str, list[str]] = {}
    for row in rows:
        label = row.get("category", "")
        if label in wanted:
            by_class.setdefault(label, []).append(row["filename"])

    result: dict[str, list[Path]] = {c: [] for c in CATEGORIES}
    for label, files in sorted(by_class.items()):
        category = ESC50_MAP[label]
        dest_dir = out / category / label
        dest_dir.mkdir(parents=True, exist_ok=True)
        for name in sorted(files)[:per_class]:
            dest = dest_dir / (Path(name).stem + ".wav")
            if dest.is_file():
                result[category].append(dest)
                continue
            url = _ESC50_AUDIO_URL.format(name=name)
            try:
                with _urlopen(url, timeout) as resp:
                    raw = resp.read()
                audio, sr = sf.read(io.BytesIO(raw), dtype="float32", always_2d=True)
                mono = audio.mean(axis=1)
                if sr != target_sr:
                    from ..audio.io import resample

                    mono = resample(mono, sr, target_sr)
                save_wav(dest, mono, target_sr)
                result[category].append(dest)
                log.debug("fetched %s -> %s", name, dest)
            except Exception as exc:
                log.warning("failed to fetch ESC-50 clip %s: %s", name, exc)
    total = sum(len(v) for v in result.values())
    log.info("ESC-50 subset: %d clips across %d classes", total, len(by_class))
    return result


def fetch_librispeech_subset(
    out_dir: Path | str,
    n_utterances: int = 40,
    min_speakers: int = 10,
    min_duration_s: float = 3.0,
    max_duration_s: float = 12.0,
    target_sr: int = 48000,
    timeout: float = 60.0,
) -> list[Path]:
    """Stream LibriSpeech dev-clean and stop as soon as enough utterances are found.

    The full archive is 337 MB; stopping early typically transfers a few tens of MB.
    Files are grouped by speaker so the builder can split by speaker.
    """
    out = Path(out_dir)
    existing = sorted(out.rglob("*.wav"))
    if len(existing) >= n_utterances:
        log.info("reusing %d cached speech files in %s", len(existing), out)
        return existing[:n_utterances]

    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    speakers: set[str] = set()
    try:
        with _urlopen(_LIBRISPEECH_URL, timeout) as resp:
            with tarfile.open(fileobj=resp, mode="r|gz") as tar:
                for member in tar:
                    if not member.isfile() or not member.name.endswith(".flac"):
                        continue
                    parts = Path(member.name).parts
                    speaker = parts[-3] if len(parts) >= 3 else "unknown"
                    # Spread across speakers: at most a few utterances each.
                    if sum(1 for p in written if p.parent.name == speaker) >= max(
                        1, n_utterances // min_speakers
                    ):
                        continue
                    fh = tar.extractfile(member)
                    if fh is None:
                        continue
                    try:
                        audio, sr = sf.read(io.BytesIO(fh.read()), dtype="float32", always_2d=True)
                    except Exception:
                        continue
                    mono = audio.mean(axis=1)
                    dur = len(mono) / sr
                    if not (min_duration_s <= dur <= max_duration_s):
                        continue
                    if sr != target_sr:
                        from ..audio.io import resample

                        mono = resample(mono, sr, target_sr)
                    dest = out / speaker / (Path(member.name).stem + ".wav")
                    save_wav(dest, mono, target_sr)
                    written.append(dest)
                    speakers.add(speaker)
                    if len(written) >= n_utterances and len(speakers) >= min_speakers:
                        break
    except (urllib.error.URLError, TimeoutError, OSError, tarfile.TarError) as exc:
        log.warning("LibriSpeech download failed or was interrupted (%s)", exc)
    log.info("clean speech: %d utterances from %d speakers", len(written), len(speakers))
    return sorted(written)


# ------------------------------------------------------------------- synthetic


def _pink(n: int, rng: np.random.Generator) -> np.ndarray:
    """Approximate 1/f noise via spectral shaping."""
    spec = rng.standard_normal(n // 2 + 1) + 1j * rng.standard_normal(n // 2 + 1)
    f = np.arange(len(spec))
    spec /= np.sqrt(np.maximum(f, 1.0))
    return np.fft.irfft(spec, n=n).astype(np.float32)


def synthesise_noise(kind: str, duration_s: float, sample_rate: int, rng: np.random.Generator) -> np.ndarray:
    """Parametric stand-in for one defence noise type."""
    n = int(duration_s * sample_rate)
    t = np.arange(n, dtype=np.float64) / sample_rate

    if kind == "vehicle_engine":
        f0 = rng.uniform(45, 90)
        sig = sum(
            (1.0 / (k**1.3)) * np.sin(2 * np.pi * f0 * k * t + rng.uniform(0, 6.28))
            for k in range(1, 14)
        )
        sig = sig * (1.0 + 0.12 * np.sin(2 * np.pi * rng.uniform(0.3, 1.2) * t))
        sig = sig + 0.25 * _pink(n, rng)
    elif kind == "rotor_wash":
        blade = rng.uniform(14, 22)
        env = 1.0 + 0.75 * np.sign(np.sin(2 * np.pi * blade * t)) * np.abs(
            np.sin(2 * np.pi * blade * t)
        ) ** 0.4
        sig = _pink(n, rng) * env + 0.3 * np.sin(2 * np.pi * blade * 6 * t)
    elif kind == "wind_buffeting":
        base = _pink(n, rng)
        gust = 1.0 + 0.9 * np.abs(np.sin(2 * np.pi * rng.uniform(0.05, 0.25) * t))
        sig = base * gust
    elif kind == "radio_hiss":
        sig = rng.standard_normal(n) * 0.6
    elif kind == "generator":
        f0 = rng.uniform(95, 130)
        sig = sum(np.sin(2 * np.pi * f0 * k * t) / k for k in range(1, 8)) + 0.4 * _pink(n, rng)
    elif kind == "siren":
        sweep = rng.uniform(0.25, 0.7)
        f = 700 + 500 * np.sin(2 * np.pi * sweep * t)
        sig = np.sin(2 * np.pi * np.cumsum(f) / sample_rate) + 0.35 * np.sin(
            4 * np.pi * np.cumsum(f) / sample_rate
        )
    elif kind == "drone_buzz":
        f0 = rng.uniform(110, 190)
        sig = sum(
            np.sin(2 * np.pi * f0 * k * t + rng.uniform(0, 6.28)) / (k**0.7) for k in range(1, 9)
        )
        sig *= 1.0 + 0.2 * np.sin(2 * np.pi * rng.uniform(1.0, 3.0) * t)
    elif kind == "crowd_babble":
        sig = np.zeros(n)
        for _ in range(12):
            f0 = rng.uniform(90, 240)
            env = np.maximum(0.0, np.sin(2 * np.pi * rng.uniform(1.5, 4.0) * t + rng.uniform(0, 6.28)))
            voice = sum(np.sin(2 * np.pi * f0 * k * t) / k for k in range(1, 6))
            sig += voice * env * rng.uniform(0.3, 1.0)
    elif kind == "vehicle_passby":
        centre = rng.uniform(0.3, 0.7) * duration_s
        env = np.exp(-((t - centre) ** 2) / (2 * (duration_s * 0.12) ** 2))
        doppler = 1.0 + 0.12 * np.tanh((t - centre) * 4.0)
        f0 = rng.uniform(60, 110)
        sig = sum(np.sin(2 * np.pi * f0 * k * doppler * t) / k for k in range(1, 10))
        sig = (sig + 0.5 * _pink(n, rng)) * env
    elif kind in ("gunshot", "machine_gun", "artillery", "explosion", "mechanical_clank"):
        sig = np.zeros(n)
        if kind == "machine_gun":
            times = np.arange(0.05, duration_s - 0.05, rng.uniform(0.08, 0.13))
            decay = 0.035
        elif kind == "artillery":
            times = np.array([rng.uniform(0.1, max(0.2, duration_s - 1.0))])
            decay = 0.5
        elif kind == "explosion":
            times = np.array([rng.uniform(0.1, max(0.2, duration_s - 1.0))])
            decay = 0.8
        elif kind == "mechanical_clank":
            times = np.arange(0.1, duration_s - 0.1, rng.uniform(0.3, 0.9))
            decay = 0.02
        else:
            times = np.array([rng.uniform(0.1, max(0.2, duration_s - 0.3))])
            decay = 0.06
        for onset in times:
            i0 = int(onset * sample_rate)
            length = min(int(decay * 6 * sample_rate), n - i0)
            if length <= 8:
                continue
            tt = np.arange(length) / sample_rate
            burst = rng.standard_normal(length) * np.exp(-tt / decay)
            if kind in ("artillery", "explosion"):
                # Low-frequency thump plus the broadband crack.
                burst += 1.6 * np.sin(2 * np.pi * rng.uniform(25, 55) * tt) * np.exp(-tt / (decay * 0.8))
            sig[i0 : i0 + length] += burst
    else:
        raise ValueError(f"unknown synthetic noise kind: {kind}")

    sig = np.asarray(sig, dtype=np.float32)
    peak = float(np.max(np.abs(sig))) or 1.0
    return (sig / peak * 0.9).astype(np.float32)


SYNTHETIC_TAXONOMY: dict[NoiseCategory, tuple[str, ...]] = {
    "stationary": ("vehicle_engine", "rotor_wash", "wind_buffeting", "radio_hiss", "generator"),
    "non_stationary": ("siren", "drone_buzz", "crowd_babble", "vehicle_passby"),
    "impulsive": ("gunshot", "machine_gun", "artillery", "explosion", "mechanical_clank"),
}


def synthesise_fallback_corpus(
    out_dir: Path | str,
    per_kind: int = 3,
    duration_s: float = 6.0,
    sample_rate: int = 48000,
    seed: int = 20260908,
) -> dict[str, list[Path]]:
    """Write a procedural noise corpus covering every category."""
    out = Path(out_dir)
    rng = np.random.default_rng(seed)
    result: dict[str, list[Path]] = {c: [] for c in CATEGORIES}
    for category, kinds in SYNTHETIC_TAXONOMY.items():
        for kind in kinds:
            for i in range(per_kind):
                dest = out / category / f"synthetic_{kind}" / f"{kind}_{i:02d}.wav"
                if not dest.is_file():
                    sig = synthesise_noise(kind, duration_s, sample_rate, rng)
                    save_wav(dest, sig, sample_rate)
                result[category].append(dest)
    log.info("synthetic noise corpus: %d files", sum(len(v) for v in result.values()))
    return result


# ---------------------------------------------------------------- registry io


def index_noise_dir(noise_dir: Path | str) -> dict[str, list[Path]]:
    """Group the noise directory by our taxonomy using the directory layout."""
    root = Path(noise_dir)
    out: dict[str, list[Path]] = {c: [] for c in CATEGORIES}
    for category in CATEGORIES:
        d = root / category
        if d.is_dir():
            out[category] = sorted(p for p in d.rglob("*.wav") if p.is_file())
    return out


def noise_type_of(path: Path) -> str:
    """The specific noise type is the immediate parent directory name."""
    return path.parent.name.replace("synthetic_", "")


def category_of(path: Path) -> str:
    for part in path.parts[::-1]:
        if part in CATEGORIES:
            return part
    return "unknown"


def write_source_manifest(path: Path | str, speech: list[Path], noise: dict[str, list[Path]]) -> Path:
    """Record exactly which source files the evaluation set was built from."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "corpora": [c.as_dict() for c in CORPORA],
        "excluded": [{"name": n, "reason": r} for n, r in EXCLUDED],
        "speech_files": [str(s) for s in speech],
        "speech_speakers": sorted({s.parent.name for s in speech}),
        "noise_files": {k: [str(v) for v in vs] for k, vs in noise.items()},
        "noise_types": {
            k: sorted({noise_type_of(v) for v in vs}) for k, vs in noise.items()
        },
        "esc50_stand_ins": ESC50_STAND_IN,
    }
    p.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return p


def load_speech_files(clean_dir: Path | str) -> list[Path]:
    return sorted(p for p in Path(clean_dir).rglob("*.wav") if p.is_file())


def speaker_of(path: Path) -> str:
    return path.parent.name


def read_audio_48k(path: Path) -> np.ndarray:
    return load_audio(path, target_sr=48000, mono=True)
