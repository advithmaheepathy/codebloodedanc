def write_licenses_md(path: Path | str = "LICENSES.md") -> Path:
    """Generate LICENSES.md from the registry."""
    p = Path(path)
    lines = [
        "# Data and model licences",
        "",
        "Generated by `anc licenses` from `anc_defence/dataset/sources.py`. Every corpus, model and",
        "simulation tool that contributes to the evaluation set or the runtime path is listed here.",
        "",
        "## In use",
        "",
        "| Source | Licence | Commercial use | Used for |",
        "| --- | --- | --- | --- |",
    ]
    for c in CORPORA:
        link = f"[{c.name}]({c.url})" if c.url else c.name
        lines.append(f"| {link} | {c.licence} | {'yes' if c.commercial_use else 'NO'} | {c.used_for} |")
    lines += ["", "### Notes", ""]
    for c in CORPORA:
        if c.notes:
            lines.append(f"- **{c.name}** ({c.licence}): {c.notes}")
    lines += [
        "",
        "## Considered and not used",
        "",
    ]
    for name, reason in EXCLUDED:
        lines.append(f"- **{name}**: {reason}")
    lines += [
        "",
        "## Consequence",
        "",
        "**The runtime path is clean.** DeepFilterNet3 is MIT/Apache-2.0, and everything this",
        "repository adds is MIT. Nothing in the shipped pipeline carries a restriction.",
        "",
        "**The evaluation audio is not.** `dataset_plain` was supplied to this project and its",
        "provenance was not verified here; the filenames point at LibriSpeech (CC BY 4.0) for speech",
        "and ESC-50 (CC BY-NC 3.0) for most of the non-gunshot noise, while the gunshot material's",
        "terms are unknown. ESC-50 alone makes the set **non-commercial**. Before publishing results",
        "or redistributing anything:",
        "",
        "1. confirm the source and licence of the gunshot corpus (4385 of 5000 examples),",
        "2. confirm the ESC-50 attribution requirement is met,",
        "3. keep the audio out of any public release of this repository - `.gitignore` already",
        "   excludes `dataset_plain/` and `data/`.",
        "",
        "Retraining or redistribution on a permissive footing would mean swapping the noise for",
        "FSD50K or MUSAN clips, both of which are licensed for that use.",
        "",
    ]
    p.write_text("\n".join(lines), encoding="utf-8")
    log.info("wrote %s", p)
    return p


